package com.github.vodobryshkin.islab1.backend.service;

/**
 * Результат изменения или удаления объекта.
 */
public enum Outcome {
    /** Изменение выполнено. */
    DONE,
    /** Объекта с указанным ID нет. */
    NOT_FOUND,
    /** Связанного объекта, указанного по ID в запросе, нет; ничего не изменено. */
    REFERENCE_NOT_FOUND,
    /** На объект ссылаются другие объекты; удаление отменено. */
    IN_USE,
    /** Значение, которое должно быть уникальным, уже занято; ничего не изменено. */
    CONFLICT
}
